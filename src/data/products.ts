export const PRODUCTS: Product[] = SEED_PRODUCTS.map((seed, index) => {
  const catImg = getCategoryImage(seed.categoryId);
  const stock = seed.stockQuantity ?? ((index % 7 === 0) ? 6 : 24 + (index % 40));
  return {
    id: seed.id,
    name: seed.name,
    slug: seed.name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/(^-|-$)/g, ''),
    categoryId: seed.categoryId,
    subcategory: seed.subcategory,
    description: seed.description,
    image: catImg,
    images: [catImg, STORE_IMAGES.yellowBox, STORE_IMAGES.marketBasket],
    price: seed.price,
    originalPrice: seed.originalPrice,
    unit: seed.unit,
    variants: seed.variants,
    stockQuantity: stock,
    availability: stock <= 8 ? 'low_stock' : 'in_stock',
    rating: seed.rating,
    reviewCount: seed.reviewCount,
    featured: Boolean(seed.featured),
    bestSelling: Boolean(seed.bestSelling),
    newArrival: Boolean(seed.newArrival),
    trending: Boolean(seed.trending),
    isDiscounted: Boolean(seed.originalPrice && seed.originalPrice > seed.price),
    tags: seed.tags,
    specifications: [
      { label: 'Package Size', value: seed.unit },
      { label: 'Subcategory', value: seed.subcategory },
      { label: 'Storage', value: seed.categoryId === 'meat-poultry' || seed.categoryId === 'fish-seafood' || seed.categoryId === 'dairy-eggs' ? 'Keep chilled or frozen as labelled' : 'Store in a cool, dry pantry' },
      { label: 'Source', value: 'Curated WACO Store Batch (Illustrative)' },
    ],
    reviews: DEFAULT_REVIEWS,
  };
});

export function getProductBySlug(slug: string): Product | undefined {
  return PRODUCTS.find((p) => p.slug === slug || p.id === slug);
}

export function getProductById(id: string): Product | undefined {
  return PRODUCTS.find((p) => p.id === id);
}

export function getProductsByCategory(categoryId: string): Product[] {
  return PRODUCTS.filter((p) => p.categoryId === categoryId);
}
